def samples_dir() -> Path:
    """Resolve the repo's ``data/samples`` directory.

    Works when the backend runs with ``cwd=backend`` (``uvicorn app.main:app``)
    and from any other working directory, because the primary candidate is
    derived from this file's location (``backend/connectors/`` -> repo root).

    Raises:
        FileNotFoundError: If no candidate directory containing the sample
            CSVs exists.
    """
    package_dir = Path(__file__).resolve().parent  # .../backend/connectors
    candidates = [
        package_dir.parent.parent / "data" / "samples",  # repo root layout
        Path.cwd() / "data" / "samples",
        Path.cwd().parent / "data" / "samples",
        package_dir / "data" / "samples",
    ]
    for candidate in candidates:
        if (candidate / "saas_churn.csv").is_file():
            return candidate
    checked = ", ".join(str(candidate) for candidate in candidates)
    raise FileNotFoundError(
        "Sample datasets not found: expected the 4 generated CSVs "
        f"(starting with saas_churn.csv) in one of: {checked}. "
        "Run `python scripts/generate_samples.py` from the repo root to create them."
    )


@lru_cache(maxsize=1)
def _load_data_dictionaries() -> dict[str, dict[str, dict[str, str]]]:
    """Parse ``DATA_DICTIONARIES.md`` into ``{sample_id: {column: {...}}}``.

    Expected markdown shape (per dataset section)::

        ## saas_churn
        | column | type | units | description |
        | --- | --- | --- | --- |
        | customer_id | string | - | Unique customer identifier |

    Returns {} if the file is missing so imports never crash; ``load_sample``
    then simply returns an empty ``columns`` dictionary entry.
    """
    try:
        markdown = (samples_dir() / "DATA_DICTIONARIES.md").read_text(encoding="utf-8")
    except OSError:
        return {}

    dictionaries: dict[str, dict[str, dict[str, str]]] = {}
    current: str | None = None
    section: re.Pattern[str] = re.compile(r"^##\s+([A-Za-z0-9_]+)\s*$")
    for line in markdown.splitlines():
        header_match = section.match(line.strip())
        if header_match:
            current = header_match.group(1)
            dictionaries.setdefault(current, {})
            continue
        if current and line.strip().startswith("|"):
            cells = [cell.strip() for cell in line.strip().strip("|").split("|")]
            if len(cells) < 2 or cells[0].lower() in ("", "column"):
                continue  # header or separator row
            if set(cells[0]) <= {"-", " "}:
                continue
            entry = {"type": cells[1], "units": cells[2] if len(cells) > 2 else "", "description": cells[3] if len(cells) > 3 else ""}
            dictionaries[current][cells[0]] = entry
    return dictionaries


#: ``{sample_id: {column_name: {"type", "units", "description"}}}`` parsed from
#: ``data/samples/DATA_DICTIONARIES.md`` at import time.
DATA_DICTIONARIES: dict[str, dict[str, dict[str, str]]] = _load_data_dictionaries()


def load_sample(sample_id: str) -> tuple[ParsedDataset, dict[str, Any]]:
    """Load one of the four sample datasets.

    Args:
        sample_id: One of :data:`SAMPLE_IDS`.

    Returns:
        ``(ParsedDataset, data_dictionary)`` where the dictionary carries the
        sample metadata plus per-column documentation — all JSON-safe::

            {
                "sample_id": ..., "name": ..., "description": ..., "story": ...,
                "row_count": <expected generated rows>, "path": "<csv path>",
                "columns": {col: {"type", "units", "description"}},
                "generator": "scripts/generate_samples.py (seed=20261005)",
            }

    Raises:
        KeyError: Unknown ``sample_id`` (message lists the valid ids).
        FileNotFoundError: The samples directory or CSV is missing.
    """
    if sample_id not in SAMPLE_IDS:
        raise KeyError(
            f"Unknown sample '{sample_id}'. Valid sample ids: {', '.join(SAMPLE_IDS)}"
        )
    directory = samples_dir()
    path = directory / f"{sample_id}.csv"
    if not path.is_file():
        raise FileNotFoundError(
            f"Sample CSV missing: {path}. Run `python scripts/generate_samples.py` "
            "from the repo root to generate the sample datasets."
        )
    dataset = parse_csv(path)
    meta = SAMPLE_META[sample_id]
    dictionary: dict[str, Any] = {
        "sample_id": sample_id,
        "name": meta["name"],
        "description": meta["description"],
        "story": meta["story"],
        "row_count": meta["row_count"],
        "path": str(path),
        "columns": dict(DATA_DICTIONARIES.get(sample_id, {})),
        "generator": "scripts/generate_samples.py (seed=20261005)",
    }
    return dataset, dictionary
