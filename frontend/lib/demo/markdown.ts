/**
 * Demo-mode Markdown renderer for reports. Mirrors the pinned backend contract
 * `render_markdown(report) -> str` (Agent 6) closely enough for offline demos.
 */
import type { Report } from "@/lib/types";

function strengthLine(strength: Report["insights"][number]["strength"]): string {
  switch (strength) {
    case "high":
      return "**Strength:** high";
    case "medium":
      return "**Strength:** medium";
    default:
      return "**Strength:** low";
  }
}

export function renderMarkdown(report: Report): string {
  const out: string[] = [];

  out.push(`# ${report.title}`);
  out.push("");
  out.push(`> **Mission:** ${report.mission}`);
  out.push("");
  out.push(`*Style: ${report.style} · Generated by AgentForge (demo mode — simulated data)*`);
  out.push("");

  out.push("## Executive summary");
  out.push("");
  out.push(report.executive_summary);
  out.push("");

  out.push("## Key insights (ranked)");
  out.push("");
  report.insights.forEach((ins, i) => {
    out.push(`### ${i + 1}. ${ins.title}`);
    out.push("");
    out.push(ins.detail);
    out.push("");
    out.push(strengthLine(ins.strength));
    if (ins.evidence.length) {
      out.push("");
      out.push("**Evidence:**");
      out.push("");
      for (const e of ins.evidence) out.push(`- ${e}`);
    }
    out.push("");
  });

  if (report.charts.length) {
    out.push("## Charts");
    out.push("");
    for (const c of report.charts) {
      out.push(`### ${c.title}`);
      out.push("");
      out.push(`*Type:* \`${c.kind}\` · *X:* ${c.x_label || "—"} · *Y:* ${c.y_label || "—"}`);
      out.push("");
      out.push("| Label | X | Y |");
      out.push("|---|---|---|");
      for (const p of c.data) {
        out.push(`| ${p.label} | ${p.x} | ${p.y} |`);
      }
      out.push("");
      if (c.notes) {
        out.push(`*${c.notes}*`);
        out.push("");
      }
    }
  }

  if (report.predictions.length) {
    out.push("## Predictions");
    out.push("");
    report.predictions.forEach((p, i) => {
      out.push(`### ${i + 1}. ${p.claim}`);
      out.push("");
      out.push(`**Confidence:** ${Math.round(p.confidence * 100)}%`);
      out.push("");
      out.push(`**Basis:** ${p.basis}`);
      out.push("");
    });
  }

  if (report.recommendations.length) {
    out.push("## Ranked recommendations");
    out.push("");
    out.push("| # | Recommendation | Action | Expected impact | Effort |");
    out.push("|---|---|---|---|---|");
    const sorted = [...report.recommendations].sort((a, b) => a.priority - b.priority);
    for (const r of sorted) {
      out.push(`| ${r.priority} | ${r.title} | ${r.action} | ${r.expected_impact} | ${r.effort} |`);
    }
    out.push("");
  }

  if (report.appendix) {
    out.push("## Appendix — method & caveats");
    out.push("");
    out.push(report.appendix);
    out.push("");
  }

  out.push("---");
  out.push("");
  out.push("*Report generated by an AgentForge team: planner → researcher → analyst → forecaster → critic.*");
  out.push("");

  return out.join("\n");
}
